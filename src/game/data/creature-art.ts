/** 未配置立绘的造物／未知物种保留已有图片或 emoji 兜底。 */
export function getCreatureImage(speciesId: string, fallback?: string): string | undefined {
  return CREATURE_IMAGES[speciesId] ?? fallback;
}

/** 已确认取消额外投影的统一像素稿；路径跟随上方配置。 */
export function isUnifiedCreatureArt(src?: string): boolean {
  return !!src && ['momo', 'mimi', 'mimi_king', 'coal'].some(id => CREATURE_IMAGES[id] === src);
}
